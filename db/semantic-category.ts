export function categoryRevision(categories: Array<{ id: string; name: string; replacement_id?: string | null }>) {
  const value = JSON.stringify(categories.filter(c => !c.replacement_id).map(c => [c.id, c.name]).sort((a, b) => a[0].localeCompare(b[0])));
  let hash = 2166136261;
  for (let i = 0; i < value.length; i++) hash = Math.imul(hash ^ value.charCodeAt(i), 16777619);
  return `semantic-v1-${hash >>> 0}`;
}
